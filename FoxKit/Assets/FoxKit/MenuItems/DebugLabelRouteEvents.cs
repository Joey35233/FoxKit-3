		[MenuItem("FoxKit/Debug/Label Route Events")]
		private static void OnLabelRouteEvents()
		{
			string output = "";

			foreach (string name in EventNames)
			{
				StrCode32 hash = new StrCode32(name);
				
				if (NodeEventHashes.Contains(HashingBitConverter.StrCode32ToUInt32(hash)))
					output += $"{name}, {hash}, Node\n";
				else if (EdgeEventHashes.Contains(HashingBitConverter.StrCode32ToUInt32(hash)))
					output += $"{name}, {hash}, Edge\n";
				else
					output += $"{name}, {hash}, Unknown\n";
			}

			Debug.Log(output);
		}
	}
